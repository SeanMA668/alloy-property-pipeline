#!/usr/bin/env python3
"""
calphad_vs_ml.py - Does the ML phase model's ranking agree with Thermo-Calc (TCHEA6 v6.1)?

For every W-Mo-Ta-Nb-V alloy with a Thermo-Calc sweep in data/calphad/, this script
recomputes the ML model's P(single-phase BCC) for that exact composition and compares
it with the CALPHAD result:

  - split temperature: highest T at which two BCC phases coexist (lower is better;
    an alloy single-phase down to 500 C is assigned 500 C, the bottom of the sweep)
  - single-phase to 500 C: yes / no

Agreement is measured by Spearman rank correlation between P(BCC) and split
temperature (a useful model should give a clearly negative value), with an exact
permutation p-value because the sample is small. The same correlation is reported for
each input feature, to show what the CALPHAD split actually tracks.

Writes calphad_vs_ml.md. Usage: python calphad_vs_ml.py
"""
from __future__ import annotations

import contextlib
import io
import itertools
import math
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

import calphad_summary as cs
import hea_model as hm
from hea_properties import CANDIDATES

HERE = Path(__file__).parent
SWEEP_MIN = 500.0


def compositions() -> dict[str, dict[str, float]]:
    comps = {}
    for (n, (label, _)), (name, c) in zip(cs.COMPOSITIONS.items(), CANDIDATES.items()):
        comps[f"#{n}"] = c
    extra = HERE / "calphad_extra_points.csv"  # runs at compositions other than planned (e.g. mass-% entry)
    for f in [HERE / "calphad_test_points.csv", *sorted(HERE.glob("calphad_round*_points.csv")),
              *([extra] if extra.exists() else [])]:
        for _, r in pd.read_csv(f).iterrows():
            comps[r["id"]] = {e: r[e] / 100 for e in hm.ELEMENTS}
    return comps


def file_for(key: str) -> Path | None:
    stem = f"hea_{key.lstrip('#')}_" if key.startswith("#") else f"hea_{key}."
    hits = sorted(p for p in (HERE / "data" / "calphad").glob("hea_*.csv")
                  if p.name.startswith(stem) and "scheil" not in p.name)
    return hits[0] if hits else None


def perm_pvalue(x, y, n_max=200000, seed=0) -> float:
    """Two-sided permutation p-value for Spearman's rho (exact when n! is small)."""
    rho0 = abs(spearmanr(x, y).statistic)
    y = np.asarray(y)
    n = len(y)
    if math.factorial(n) <= n_max:
        perms = itertools.permutations(range(n))
        vals = [abs(spearmanr(x, y[list(p)]).statistic) for p in perms]
    else:
        rng = np.random.default_rng(seed)
        vals = [abs(spearmanr(x, rng.permutation(y)).statistic) for _ in range(n_max)]
    return float(np.mean(np.array(vals) >= rho0 - 1e-12))


def main():
    with contextlib.redirect_stdout(io.StringIO()):
        d = hm.load_element_data()
        exp, _ = hm.load_experimental(hm.DATA_PATH)
    rf, _, _ = hm.train_classifier(exp, 42)

    rows, missing = [], []
    for key, comp in compositions().items():
        f = file_for(key)
        s = cs.summarise(f) if f else None
        if s is None or not s["complete"]:
            missing.append(key)
            continue
        C = np.array([[comp[e] for e in hm.ELEMENTS]])
        feats = hm.compute_features(C, d)
        p = float(rf.predict_proba(feats[hm.FEATURES].to_numpy())[0, 1])
        split = max(s["extra"]["second BCC (A2)"][0], SWEEP_MIN) if s["extra"] else SWEEP_MIN
        rows.append({"alloy": key, **{e: round(100 * comp[e], 1) for e in hm.ELEMENTS},
                     "p_bcc": p, "split_C": split, "single_to_500": not s["extra"],
                     "solidus_C": s["solidus"],
                     **{k: float(feats[k].iloc[0]) for k in hm.FEATURES}})
    df = pd.DataFrame(rows).sort_values("p_bcc", ascending=False).reset_index(drop=True)

    rho = spearmanr(df["p_bcc"], df["split_C"]).statistic
    pval = perm_pvalue(df["p_bcc"].to_numpy(), df["split_C"].to_numpy())
    feat_rho = {k: spearmanr(df[k], df["split_C"]).statistic for k in hm.FEATURES}
    top_half = df["p_bcc"] >= df["p_bcc"].median()

    L = ["# Does the ML phase model agree with Thermo-Calc?\n",
         f"{len(df)} W-Mo-Ta-Nb-V alloys with complete Thermo-Calc (TCHEA6 v6.1) sweeps from 500 to "
         f"3000 °C, compared with the ML model's P(single-phase BCC) for the same composition. "
         + (f"Not included (no complete sweep yet): {', '.join(missing)}. " if missing else "")
         + "Generated by `calphad_vs_ml.py`.\n",
         "## Result\n",
         f"- **Rank agreement:** Spearman ρ between P(BCC) and the CALPHAD split temperature is "
         f"**{rho:+.2f}** (permutation p = {pval:.2f}, n = {len(df)}). A useful model would give a "
         "clearly negative value: higher P(BCC), lower split temperature.",
         f"- **Single-phase to 500 °C:** {int(df['single_to_500'].sum())} of {len(df)} alloys. "
         f"Among the model's top half by P(BCC): {int(df.loc[top_half, 'single_to_500'].sum())} of "
         f"{int(top_half.sum())}; bottom half: {int(df.loc[~top_half, 'single_to_500'].sum())} of "
         f"{int((~top_half).sum())}.",
         "",
         "| Alloy | W | Mo | Ta | Nb | V | ML P(BCC) | CALPHAD split (°C) | Solidus (°C) |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for _, r in df.iterrows():
        split = "none ≥ 500" if r["single_to_500"] else f"{r['split_C']:.0f}"
        L.append(f"| {r['alloy']} | {r['W']} | {r['Mo']} | {r['Ta']} | {r['Nb']} | {r['V']} | "
                 f"{r['p_bcc']:.3f} | {split} | {r['solidus_C']:.0f} |")
    L.append("")
    L.append("## What the CALPHAD split tracks (exploratory)\n")
    L.append("Spearman ρ between each model input and the split temperature, same alloys. With "
             f"n = {len(df)} these are indications, not findings.\n")
    L.append("| Feature | ρ with split temperature |")
    L.append("|---|---:|")
    for k, v in sorted(feat_rho.items(), key=lambda kv: -abs(kv[1])):
        L.append(f"| {k} | {v:+.2f} |")
    L.append("")
    L.append("Alloys 'single-phase to 500 °C' are assigned 500 °C, so they tie at the bottom of the "
             "ranking. Both methods are models: agreement or disagreement here says nothing "
             "directly about real alloys.\n")
    (HERE / "calphad_vs_ml.md").write_text("\n".join(L))
    df.to_csv(HERE / "data" / "calphad" / "calphad_vs_ml.csv", index=False)
    print("\n".join(L))


if __name__ == "__main__":
    main()
