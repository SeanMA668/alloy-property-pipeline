#!/usr/bin/env python3
"""
ashby.py - Put the calculated alloys on the same chart as existing high-temperature metals.

Comparison data: Ansys Granta EduPack (records and ranges transcribed from the exported
table, data/edupack/edupack_comparison_table.pdf, into data/edupack/edupack_comparison.csv).
Our alloys: Thermo-Calc TCHEA6 solidus and rule-of-mixtures density
(data/calphad/study_results.csv).

Note the mismatch in kind: EduPack gives *measured* handbook ranges (melting point for pure
metals); ours are *calculated* solidus values for alloys never made.

Writes reports/figures/ashby_melting_density.png and reports/ashby.md.
Usage: python -m pipeline.ashby
"""
from __future__ import annotations

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.patches import Rectangle

from pipeline import paths as P
from pipeline.figures import BLUE, ORANGE, INK, INK2, MUTED, SURFACE  # also sets rcParams

EDUPACK = P.ROOT / "data" / "edupack" / "edupack_comparison.csv"
FINALISTS = ["R5-1", "R5-2", "R5-13", "R5-4", "T6"]
GROUP_COLOR = {"Refractory metal": "#6b6a66", "Refractory alloy": "#1f9e89",
               "Ni superalloy": "#b4459c"}


def load():
    e = pd.read_csv(EDUPACK)
    d = pd.read_csv(P.CALPHAD / "study_results.csv")
    return e, d


def chart(e: pd.DataFrame, d: pd.DataFrame, out):
    fig, ax = plt.subplots(figsize=(8.6, 5.6), dpi=160)
    for _, r in e.dropna(subset=["melt_lo_C"]).iterrows():
        c = GROUP_COLOR[r["group"]]
        w = max(r["density_hi"] - r["density_lo"], 0.12)
        h = max(r["melt_hi_C"] - r["melt_lo_C"], 30)
        x0 = (r["density_lo"] + r["density_hi"]) / 2 - w / 2
        y0 = (r["melt_lo_C"] + r["melt_hi_C"]) / 2 - h / 2
        ax.add_patch(Rectangle((x0, y0), w, h, facecolor=c, alpha=0.35, edgecolor=c, lw=1.2))
        if r["short"] == "TZM":      # same box as Mo; labelled together
            continue
        label = "Mo, TZM" if r["short"] == "Mo" else r["short"]
        dy = -9 if r["short"] == "Ta" else (7 if r["short"] == "Ta-10W" else 0)
        ax.annotate(label, (x0 + w, y0 + h / 2), xytext=(5, dy), textcoords="offset points",
                    va="center", fontsize=8.5, color=c, fontweight="bold")
    sp = d[d["single_phase_500C"]]
    ax.scatter(sp["density_gcc"], sp["solidus_C"], s=22, color=BLUE, alpha=0.35, lw=0,
               label=f"Our single-phase alloys, calculated ({len(sp)})", zorder=3)
    f = d.set_index("alloy").loc[FINALISTS]
    ax.scatter(f["density_gcc"], f["solidus_C"], s=70, color=BLUE, edgecolor=SURFACE, lw=1.3,
               label="Finalists + T6 (calculated solidus)", zorder=4)
    for a, r in f.iterrows():
        off = (-6, 6) if a == "T6" else (6, -3)
        ax.annotate(a, (r["density_gcc"], r["solidus_C"]), xytext=off, ha="right" if a == "T6" else "left",
                    textcoords="offset points", fontsize=8, color=INK2)
    for g, c in GROUP_COLOR.items():
        ax.scatter([], [], marker="s", s=60, color=c, alpha=0.5, label=f"{g} (EduPack)")
    ax.set_xlabel("Density (g/cm³)")
    ax.set_ylabel("Melting point / solidus (°C)")
    ax.set_xlim(7.5, 20.5)
    ax.set_ylim(1100, 3600)
    ax.grid(True)
    ax.set_title("Where the calculated alloys sit among existing high-temperature metals",
                 loc="left", color=INK, fontsize=11.5, fontweight="bold")
    ax.legend(loc="lower right", frameon=False, fontsize=8, labelcolor=INK2)
    fig.text(0.01, 0.005, "EduPack: measured handbook ranges. Ours: Thermo-Calc TCHEA6 solidus, "
             "rule-of-mixtures density; not yet made. CMSX-4 has no melting point in EduPack.",
             fontsize=7, color=MUTED)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(out)
    plt.close(fig)


def main():
    e, d = load()
    out = P.REPORTS / "figures" / "ashby_melting_density.png"
    chart(e, d, out)
    f = d.set_index("alloy").loc[FINALISTS]
    cs = pd.read_csv(P.CALPHAD / "cost_supply.csv").set_index("alloy")
    L = ["# Comparison with existing high-temperature metals\n",
         "Generated by `pipeline/ashby.py`. Existing materials: Ansys Granta EduPack records "
         "(`data/edupack/`), measured handbook ranges. Our alloys: calculated (Thermo-Calc "
         "TCHEA6 solidus, rule-of-mixtures density), never made.\n",
         "![Melting point vs density](figures/ashby_melting_density.png)\n",
         "## EduPack data used\n",
         "| Material | Density (g/cm³) | Melting point (°C) | Yield strength, RT (MPa) | Max service T (°C) | Price ($/kg) |",
         "|---|---|---|---|---|---|"]
    rng = lambda lo, hi, f="{:g}": "–" if pd.isna(lo) else (f.format(lo) if lo == hi else f"{f.format(lo)}–{f.format(hi)}")
    for _, r in e.iterrows():
        L.append(f"| {r['short']} | {rng(r['density_lo'], r['density_hi'])} | "
                 f"{rng(r['melt_lo_C'], r['melt_hi_C'])} | {rng(r['ys_lo_MPa'], r['ys_hi_MPa'])} | "
                 f"{rng(r['tmax_lo_C'], r['tmax_hi_C'])} | {rng(r['price_lo_usd_kg'], r['price_hi_usd_kg'])} |")
    L += ["",
          "## Our finalists\n",
          "| Alloy | Density (g/cm³) | Solidus (°C) | Raw-material cost, 2025 ($/kg) |",
          "|---|---:|---:|---:|"]
    for a, r in f.iterrows():
        L.append(f"| {a} | {r['density_gcc']:.2f} | {r['solidus_C']:.0f} | {cs.loc[a, 'cost_2025']:.0f} |")
    L += ["",
          "## Reading\n",
          "- **The gap the alloys aim at.** In this EduPack set nothing sits between Mo/TZM "
          "(2610–2620 °C at 10.1–10.3 g/cm³) and Ta/Ta-10W (2990–3040 °C at 16.5–16.9 g/cm³). "
          "R5-1, R5-2, R5-13 and T6 are calculated to fall in that gap (solidus 2688–2822 °C at "
          "12.7–14.9 g/cm³): hotter than Mo alloys, lighter than Ta alloys.",
          "- **R5-4 does not win on these two axes alone:** Mo and TZM are both lighter and "
          "higher-melting. Its case rests on other properties (it is the lightest finalist and "
          "the least exposed to tungsten price), which this chart does not show.",
          "- **Against Ni superalloys** (the incumbent for turbine hot sections): Inconel 718 "
          "melts at 1260–1340 °C; the finalists' calculated solidus is about 1160–1560 °C "
          "higher, at 1.4–1.8× the density.",
          "- **Price mark-up varies by element.** Comparing EduPack's finished-metal prices "
          "with the raw-material prices in `cost_supply.md`: W ($40–69 vs $48/kg) and Mo "
          "($48.5 vs $51) cost about the same finished; Ta ($375–442 vs $220) about 2×; Nb "
          "($127–145 vs $40) about 3–3.6×. So the raw-material cost understates Ta- and Nb-rich "
          "alloys most, which makes R5-1 and R5-4 relatively more expensive than "
          "`cost_supply.md` shows.",
          "",
          "## Limits\n",
          "- Calculated solidus vs measured melting point; calculated vs handbook density.",
          "- No strength comparison is drawn: our strength estimates are not reliable enough "
          "(`finalists.md` §3), and EduPack's are room-temperature values for wrought or "
          "annealed material.",
          "- EduPack 'maximum service temperature' for refractory metals reflects oxidation and "
          "recrystallisation limits; oxidation is not assessed for our alloys.\n"]
    (P.REPORTS / "ashby.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
